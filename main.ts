import { cpSync, mkdirSync, writeFileSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildDossier } from './vendor/makefun-game.ts';
const root=dirname(fileURLToPath(import.meta.url));
const destination=resolve(process.env.MAKEFUN_OUTPUT_DIR||'/output');
mkdirSync(destination,{recursive:true});
for(const folder of ['game','screenshots'])cpSync(join(root,folder),join(destination,folder),{recursive:true});
const dossier=buildDossier(destination,{text_max_bytes:163840,screenshots:{max:4,max_bytes:262144},game_max_files:993,game_max_bytes:50331648,game_path_max_bytes:1000});
writeFileSync(join(destination,'dossier.json'),dossier);
console.log('Dossier written to '+destination);
